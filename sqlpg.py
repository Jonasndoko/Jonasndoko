"""Traduction du SQL « SQLite » de GESTSCO vers PostgreSQL (module pur : aucun pilote requis, donc testable partout).

Deux services :
  - traduire(sql)            : une requête (SELECT / INSERT / UPDATE / DELETE) -> PostgreSQL ;
  - analyser_schema(script)  : le schéma SQLite (database.SCHEMA) -> instructions PostgreSQL (tables, index, déclencheurs).

Principes (voir aussi MIGRATION_POSTGRESQL.md) :
  - les noms restent ceux de l'application ; PostgreSQL les met en minuscules (les identifiants entre guillemets sont abaissés) ;
  - INTEGER -> BIGINT (SQLite a des entiers 64 bits : les montants en centimes ne doivent pas déborder) ;
    REAL -> DOUBLE PRECISION ; BLOB -> BYTEA ; TEXT ... COLLATE NOCASE -> CITEXT (clés insensibles à la casse) ;
  - AUTOINCREMENT -> GENERATED BY DEFAULT AS IDENTITY ; clés étrangères DIFFÉRABLES (PRAGMA defer_foreign_keys) ;
  - les déclencheurs « SELECT RAISE(ABORT, ...) » deviennent des fonctions PL/pgSQL (SQLSTATE 23000 : une erreur d'intégrité,
    comme sous SQLite) ; le WHEN (qui peut contenir une sous-requête, interdit par PostgreSQL) passe dans la fonction ;
  - l'ordre des NULL est celui de SQLite (NULL d'abord en croissant, en dernier en décroissant) ;
  - LIKE devient ILIKE (SQLite ignore la casse pour l'ASCII).
"""
import re
from dataclasses import dataclass, field
from functools import lru_cache

# ============================================================================ masquage des littéraux
# Les chaînes, identifiants entre guillemets et commentaires sont remplacés par des jetons \x00N\x00 : les expressions
# régulières ci-dessous ne peuvent alors jamais toucher à leur contenu.
_RE_LITTERAUX = re.compile(r"'(?:[^']|'')*'|\"(?:[^\"]|\"\")*\"|--[^\n]*|/\*.*?\*/", re.S)
_RE_JETON = re.compile(r"\x00(\d+)\x00")


def masquer(sql: str):
    """Retourne (texte masqué, liste des littéraux). Les commentaires disparaissent."""
    litteraux = []

    def remplacer(m):
        t = m.group(0)
        if t.startswith("--") or t.startswith("/*"):
            return " "
        litteraux.append(t)
        return f"\x00{len(litteraux) - 1}\x00"

    return _RE_LITTERAUX.sub(remplacer, sql), litteraux


def demasquer(texte: str, litteraux: list, echapper_pourcent=False) -> str:
    def remplacer(m):
        t = litteraux[int(m.group(1))]
        if t.startswith('"'):
            t = t.lower()                       # identifiant entre guillemets : tout est en minuscules côté PostgreSQL
        elif echapper_pourcent:
            t = t.replace("%", "%%")
        return t
    return _RE_JETON.sub(remplacer, texte)


def _nouveau_litteral(litteraux: list, texte: str) -> str:
    litteraux.append(texte)
    return f"\x00{len(litteraux) - 1}\x00"


# ============================================================================ outils de découpage
def _parentheses_equilibrees(texte: str, debut: int) -> int:
    """Index de la parenthèse fermante qui correspond à celle de `debut` (texte masqué)."""
    profondeur = 0
    for i in range(debut, len(texte)):
        if texte[i] == "(":
            profondeur += 1
        elif texte[i] == ")":
            profondeur -= 1
            if profondeur == 0:
                return i
    raise ValueError("parenthèse non fermée")


def _decouper_virgules(texte: str) -> list:
    """Découpe aux virgules du niveau 0 (texte masqué)."""
    morceaux, profondeur, debut = [], 0, 0
    for i, c in enumerate(texte):
        if c == "(":
            profondeur += 1
        elif c == ")":
            profondeur -= 1
        elif c == "," and profondeur == 0:
            morceaux.append(texte[debut:i].strip())
            debut = i + 1
    reste = texte[debut:].strip()
    if reste:
        morceaux.append(reste)
    return morceaux


def decouper_instructions(script: str) -> list:
    """Découpe un script en instructions (aux « ; » hors littéraux ; un déclencheur finit à « END; »)."""
    masque, litteraux = masquer(script)
    instructions, courante = [], []
    for morceau in masque.split(";"):
        courante.append(morceau)
        texte = ";".join(courante)
        if re.match(r"\s*CREATE\s+TRIGGER\b", texte, re.I) and not re.search(r"\bEND\s*$", morceau, re.I):
            continue                                  # « ; » à l'intérieur du corps du déclencheur
        if texte.strip():
            instructions.append(demasquer(texte.strip(), litteraux))
        courante = []
    if courante and ";".join(courante).strip():
        instructions.append(demasquer(";".join(courante).strip(), litteraux))
    return instructions


# ============================================================================ règles de traduction communes
def _glob_vers_regex(glob: str) -> str:
    """Motif GLOB de SQLite (sans guillemets) -> expression régulière POSIX ancrée."""
    sortie, i = ["^"], 0
    while i < len(glob):
        c = glob[i]
        if c == "*":
            sortie.append(".*")
        elif c == "?":
            sortie.append(".")
        elif c == "[":
            j = i + 1
            if j < len(glob) and glob[j] == "^":
                j += 1
            if j < len(glob) and glob[j] == "]":
                j += 1
            j = glob.find("]", j)
            if j < 0:
                sortie.append("\\[")
            else:
                sortie.append(glob[i:j + 1])
                i = j
        elif c in ".^$+(){}|\\":
            sortie.append("\\" + c)
        else:
            sortie.append(c)
        i += 1
    sortie.append("$")
    return "".join(sortie)


def _regles_expression(m: str, litteraux: list) -> str:
    """Règles valables dans une requête comme dans un schéma (texte masqué)."""
    # GLOB / NOT GLOB
    def glob(match):
        negation = "!~" if match.group(1) else "~"
        brut = litteraux[int(match.group(2))]
        return f"{negation} " + _nouveau_litteral(litteraux, "'" + _glob_vers_regex(brut[1:-1]) + "'")
    m = re.sub(r"\b(NOT\s+)?GLOB\s+\x00(\d+)\x00", glob, m, flags=re.I)

    # IS [NOT] <valeur> (égalité « sûre pour NULL » de SQLite)
    m = re.sub(r"\bIS\s+NOT\s+(?!NULL\b|DISTINCT\b)", "IS DISTINCT FROM ", m, flags=re.I)
    m = re.sub(r"\bIS\s+(?!NOT\b|NULL\b|TRUE\b|FALSE\b|UNKNOWN\b|DISTINCT\b)", "IS NOT DISTINCT FROM ", m, flags=re.I)

    # COLLATE NOCASE
    m = re.sub(r"([\w.]+)\s*(=|<>|!=)\s*(\?|\x00\d+\x00)\s+COLLATE\s+NOCASE\b", r"LOWER(\1) \2 LOWER(\3)", m, flags=re.I)
    m = re.sub(r"([\w.]+)\s+COLLATE\s+NOCASE\b", r"LOWER(\1)", m, flags=re.I)
    m = re.sub(r"\s+COLLATE\s+NOCASE\b", "", m, flags=re.I)
    return m


# ============================================================================ ORDER BY : ordre des NULL de SQLite
_TERMINATEURS = re.compile(r"\b(LIMIT|OFFSET|FETCH|FOR|UNION|INTERSECT|EXCEPT|RETURNING|ON\s+CONFLICT|WINDOW)\b", re.I)


def _ordre_nulls(m: str) -> str:
    """SQLite classe NULL avant les valeurs en croissant (après en décroissant) ; PostgreSQL fait l'inverse."""
    resultat, position = [], 0
    for debut in re.finditer(r"\bORDER\s+BY\b", m, re.I):
        if debut.start() < position:
            continue
        i, profondeur, fin = debut.end(), 0, len(m)
        while i < len(m):
            c = m[i]
            if c == "(":
                profondeur += 1
            elif c == ")":
                if profondeur == 0:
                    fin = i
                    break
                profondeur -= 1
            elif c == ";" and profondeur == 0:
                fin = i
                break
            elif profondeur == 0:
                t = _TERMINATEURS.match(m, i)
                if t and (i == 0 or not (m[i - 1].isalnum() or m[i - 1] == "_")):
                    fin = i
                    break
            i += 1
        termes = _decouper_virgules(m[debut.end():fin])
        nouveaux = []
        for t in termes:
            if re.search(r"\bNULLS\s+(FIRST|LAST)\s*$", t, re.I):
                nouveaux.append(t)
            elif re.search(r"\bDESC\s*$", t, re.I):
                nouveaux.append(t + " NULLS LAST")
            else:
                nouveaux.append(t + " NULLS FIRST")
        resultat.append(m[position:debut.end()])
        resultat.append(" " + ", ".join(nouveaux) + (" " if fin < len(m) else ""))
        position = fin
    resultat.append(m[position:])
    return "".join(resultat)


# ============================================================================ sqlite_master
# Émule la table système de SQLite (types table / index / trigger) à partir du catalogue PostgreSQL.
# `sql` des déclencheurs est le texte SQLite d'origine (utile à renvoi.py, qui retire puis recrée un déclencheur).
SQLITE_MASTER_SQL = (
    "(SELECT 'table' AS type, upper(c.relname::text) AS name, upper(c.relname::text) AS tbl_name, ''::text AS sql "
    "FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
    "WHERE n.nspname = current_schema() AND c.relkind = 'r' AND c.relname <> 'gestsco_meta' "
    "UNION ALL SELECT 'index', upper(i.relname::text), upper(t.relname::text), NULL::text "
    "FROM pg_index x JOIN pg_class i ON i.oid = x.indexrelid JOIN pg_class t ON t.oid = x.indrelid "
    "JOIN pg_namespace n ON n.oid = i.relnamespace "
    "WHERE n.nspname = current_schema() AND t.relname <> 'gestsco_meta' "
    "AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conindid = i.oid) "
    "UNION ALL SELECT 'trigger', upper(g.tgname::text), upper(t.relname::text), NULL::text "
    "FROM pg_trigger g JOIN pg_class t ON t.oid = g.tgrelid JOIN pg_namespace n ON n.oid = t.relnamespace "
    "WHERE n.nspname = current_schema() AND NOT g.tgisinternal) sqlite_master"
)


# ============================================================================ requêtes (DML)
_REGISTRE = None          # rempli par enregistrer() : clés primaires et identités du schéma


def enregistrer(script_schema: str):
    """Mémorise le schéma de l'application (clés primaires, colonnes auto-incrémentées, déclencheurs)."""
    global _REGISTRE
    _REGISTRE = analyser_schema(script_schema)
    traduire.cache_clear()
    return _REGISTRE


def registre():
    return _REGISTRE


@lru_cache(maxsize=8192)
def traduire(sql: str, avec_parametres: bool = True) -> str:
    """Traduit une requête SQLite en requête PostgreSQL (placeholders « ? » -> « %s »)."""
    m, lit = masquer(sql.strip().rstrip(";"))

    # INSERT OR IGNORE / INSERT OR REPLACE / REPLACE INTO
    suffixe = ""
    ig = re.match(r"\s*INSERT\s+OR\s+IGNORE\s+INTO\b", m, re.I)
    rp = re.match(r"\s*(INSERT\s+OR\s+REPLACE|REPLACE)\s+INTO\s+(\w+)\s*\(([^)]*)\)", m, re.I)
    if ig:
        m = re.sub(r"^\s*INSERT\s+OR\s+IGNORE\s+INTO\b", "INSERT INTO", m, flags=re.I)
        suffixe = " ON CONFLICT DO NOTHING"
    elif rp:
        table, colonnes = rp.group(2).upper(), [c.strip() for c in rp.group(3).split(",")]
        cles = [c.upper() for c in _REGISTRE.tables[table].cle] if _REGISTRE and table in _REGISTRE.tables else None
        if not cles:
            raise ValueError(f"INSERT OR REPLACE : clé primaire de {table} inconnue")
        maj = [c for c in colonnes if c.upper() not in cles]
        m = re.sub(r"^\s*(INSERT\s+OR\s+REPLACE|REPLACE)\s+INTO\b", "INSERT INTO", m, flags=re.I)
        suffixe = (f" ON CONFLICT ({', '.join(c.lower() for c in cles)}) DO "
                   + (("UPDATE SET " + ", ".join(f"{c} = EXCLUDED.{c}" for c in maj)) if maj else "NOTHING"))

    if re.match(r"\s*SELECT\s+DISTINCT\b", m, re.I):
        # PostgreSQL : en SELECT DISTINCT, ORDER BY ne peut porter que sur une colonne du SELECT (pas LOWER(colonne)) -> on trie sans casse neutralisée
        o = list(re.finditer(r"\bORDER\s+BY\b", m, re.I))
        if o:
            m = m[:o[-1].end()] + re.sub(r"\s+COLLATE\s+NOCASE\b", "", m[o[-1].end():], flags=re.I)
    m = _regles_expression(m, lit)
    m = re.sub(r"\bLIKE\b", "ILIKE", m, flags=re.I)
    m = re.sub(r"\bsqlite_master\b", lambda _: SQLITE_MASTER_SQL, m, flags=re.I)
    m = re.sub(r"\browid\b", "ctid", m, flags=re.I)
    m = _ordre_nulls(m)
    if suffixe:
        # ON CONFLICT vient avant un éventuel RETURNING
        m = m.rstrip() + suffixe
    if avec_parametres:
        m = m.replace("%", "%%").replace("?", "%s")
    return demasquer(m, lit, echapper_pourcent=avec_parametres)


# ============================================================================ schéma (DDL)
@dataclass
class CleEtrangere:
    colonnes: list
    table_ref: str
    colonnes_ref: list
    suppression: str = ""


@dataclass
class Colonne:
    nom: str
    type_sqlite: str
    defaut: str = None
    non_nul: bool = False
    unique: bool = False
    nocase: bool = False
    identite: bool = False
    controles: list = field(default_factory=list)


@dataclass
class Table:
    nom: str
    colonnes: list = field(default_factory=list)
    cle: list = field(default_factory=list)
    uniques: list = field(default_factory=list)
    controles: list = field(default_factory=list)
    cles_etrangeres: list = field(default_factory=list)
    texte_pg: str = ""

    def colonne(self, nom):
        return next(c for c in self.colonnes if c.nom.upper() == nom.upper())


@dataclass
class Index:
    nom: str
    table: str
    unique: bool
    elements: list
    condition: str
    texte_pg: str = ""


@dataclass
class Declencheur:
    nom: str
    table: str
    moment: str
    evenement: str
    colonnes: list
    condition: str
    message: str
    sql_sqlite: str
    texte_pg: list = field(default_factory=list)


@dataclass
class Schema:
    tables: dict = field(default_factory=dict)
    index: dict = field(default_factory=dict)
    declencheurs: dict = field(default_factory=dict)

    @property
    def identites(self) -> dict:
        """{TABLE: COLONNE} des colonnes auto-incrémentées."""
        return {t.nom.upper(): c.nom.upper() for t in self.tables.values() for c in t.colonnes if c.identite}

    def nocase(self, table, colonne) -> bool:
        return self.tables[table.upper()].colonne(colonne).nocase


_TYPES_PG = {"INTEGER": "BIGINT", "TEXT": "TEXT", "REAL": "DOUBLE PRECISION", "BLOB": "BYTEA", "NUMERIC": "NUMERIC"}


def type_pg(type_sqlite: str, nocase=False) -> str:
    t = (type_sqlite or "").strip().upper()
    if t == "TEXT" and nocase:
        return "CITEXT"
    return _TYPES_PG.get(t, "TEXT")


def _noms(liste: str) -> list:
    return [x.strip().strip('"').upper() for x in liste.split(",") if x.strip()]


def _analyser_table(nom: str, corps: str, lit: list) -> Table:
    table = Table(nom.upper())
    for item in _decouper_virgules(corps):
        tete = re.match(r"\s*(PRIMARY\s+KEY|UNIQUE|CHECK|FOREIGN\s+KEY|CONSTRAINT)\b", item, re.I)
        if tete:
            mot = re.sub(r"\s+", " ", tete.group(1).upper())
            if mot == "PRIMARY KEY":
                table.cle = _noms(re.search(r"\(([^)]*)\)", item).group(1))
            elif mot == "UNIQUE":
                table.uniques.append(_noms(re.search(r"\(([^)]*)\)", item).group(1)))
            elif mot == "CHECK":
                debut = item.index("(")
                table.controles.append(item[debut + 1:_parentheses_equilibrees(item, debut)])
            elif mot == "FOREIGN KEY":
                m = re.match(r"\s*FOREIGN\s+KEY\s*\(([^)]*)\)\s*REFERENCES\s+(\w+)\s*\(([^)]*)\)"
                             r"(?:\s+ON\s+DELETE\s+(CASCADE|SET\s+NULL|RESTRICT|NO\s+ACTION))?\s*$", item, re.I)
                if not m:
                    raise ValueError(f"clé étrangère non reconnue dans {nom} : {demasquer(item, lit)}")
                table.cles_etrangeres.append(CleEtrangere(_noms(m.group(1)), m.group(2).upper(), _noms(m.group(3)),
                                                          re.sub(r"\s+", " ", (m.group(4) or "").upper())))
            else:
                raise ValueError(f"contrainte non gérée dans {nom} : {demasquer(item, lit)}")
            continue
        m = re.match(r"\s*(\w+)\s+(INTEGER|TEXT|REAL|BLOB|NUMERIC)\b(.*)$", item, re.I | re.S)
        if not m:
            raise ValueError(f"colonne non reconnue dans {nom} : {demasquer(item, lit)}")
        col = Colonne(m.group(1).upper(), m.group(2).upper())
        reste = m.group(3)

        def prendre(motif, texte):
            trouve = re.search(motif, texte, re.I | re.S)
            return (trouve, texte[:trouve.start()] + " " + texte[trouve.end():]) if trouve else (None, texte)

        ref, reste = prendre(r"\bREFERENCES\s+(\w+)\s*\(([^)]*)\)(?:\s+ON\s+DELETE\s+(CASCADE|SET\s+NULL|RESTRICT|NO\s+ACTION))?", reste)
        if ref:
            table.cles_etrangeres.append(CleEtrangere([col.nom], ref.group(1).upper(), _noms(ref.group(2)),
                                                      re.sub(r"\s+", " ", (ref.group(3) or "").upper())))
        while True:                                            # CHECK (...) : parenthèses équilibrées
            c = re.search(r"\bCHECK\s*\(", reste, re.I)
            if not c:
                break
            ouvrante = c.end() - 1
            fermante = _parentheses_equilibrees(reste, ouvrante)
            col.controles.append(reste[ouvrante + 1:fermante])
            reste = reste[:c.start()] + " " + reste[fermante + 1:]
        pk, reste = prendre(r"\bPRIMARY\s+KEY(\s+AUTOINCREMENT)?", reste)
        if pk:
            table.cle = [col.nom]
            col.identite = bool(pk.group(1))
        nn, reste = prendre(r"\bNOT\s+NULL\b", reste)
        col.non_nul = bool(nn) or bool(pk)
        un, reste = prendre(r"\bUNIQUE\b", reste)
        col.unique = bool(un)
        nc, reste = prendre(r"\bCOLLATE\s+NOCASE\b", reste)
        col.nocase = bool(nc)
        df, reste = prendre(r"\bDEFAULT\s+(\x00\d+\x00|\([^)]*\)|[-+]?[\w.]+)", reste)
        if df:
            col.defaut = df.group(1)
        if reste.strip():
            raise ValueError(f"définition de colonne non gérée dans {nom}.{col.nom} : {demasquer(reste, lit).strip()}")
        table.colonnes.append(col)
    return table


def _analyser_declencheur(texte: str, m: str, lit: list) -> Declencheur:
    r = re.match(r"\s*CREATE\s+TRIGGER\s+(?:IF\s+NOT\s+EXISTS\s+)?(\w+)\s+(BEFORE|AFTER)\s+(INSERT|UPDATE|DELETE)"
                 r"(?:\s+OF\s+([\w\s,]+?))?\s+ON\s+(\w+)\s*(?:WHEN\s+(.*?))?\s*BEGIN\s+SELECT\s+RAISE\s*\(\s*ABORT\s*,"
                 r"\s*\x00(\d+)\x00\s*\)\s*;\s*END\s*$", m, re.I | re.S)
    if not r:
        raise ValueError("déclencheur non géré (seul « SELECT RAISE(ABORT, ...) » est traduit) : " + texte[:80])
    nom, moment, evenement, cols, table, quand, message = r.groups()
    quand = _regles_expression(quand, lit) if quand else ""
    message = lit[int(message)][1:-1]                           # texte entre guillemets, apostrophes doublées
    d = Declencheur(nom.upper(), table.upper(), moment.upper(), evenement.upper(), _noms(cols) if cols else [],
                    demasquer(quand, lit).strip(), message, texte.strip())
    ligne = "NEW" if d.evenement != "DELETE" else "OLD"
    corps = (f"IF {d.condition} THEN RAISE EXCEPTION USING ERRCODE = '23000', MESSAGE = '{message}'; END IF;"
             if d.condition else f"RAISE EXCEPTION USING ERRCODE = '23000', MESSAGE = '{message}';")
    of = (" OF " + ", ".join(c.lower() for c in d.colonnes)) if d.colonnes else ""
    d.texte_pg = [
        f"CREATE OR REPLACE FUNCTION trg_{d.nom.lower()}() RETURNS trigger LANGUAGE plpgsql AS $gestsco$ "
        f"BEGIN {corps} RETURN {ligne}; END; $gestsco$",
        f"DROP TRIGGER IF EXISTS {d.nom.lower()} ON {d.table.lower()}",
        f"CREATE TRIGGER {d.nom.lower()} {d.moment} {d.evenement}{of} ON {d.table.lower()} FOR EACH ROW "
        f"EXECUTE FUNCTION trg_{d.nom.lower()}()",
    ]
    return d


def _analyser_index(m: str, lit: list, schema: Schema) -> Index:
    r = re.match(r"\s*CREATE\s+(UNIQUE\s+)?INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?(\w+)\s+ON\s+(\w+)\s*\(", m, re.I)
    if not r:
        raise ValueError("index non reconnu : " + demasquer(m, lit)[:80])
    ouvrante = r.end() - 1
    fermante = _parentheses_equilibrees(m, ouvrante)
    condition = re.match(r"\s*WHERE\s+(.*)$", m[fermante + 1:], re.I | re.S)
    return Index(r.group(2).upper(), r.group(3).upper(), bool(r.group(1)),
                 _decouper_virgules(m[ouvrante + 1:fermante]),
                 condition.group(1).strip() if condition else "")
    # (le texte PostgreSQL est produit plus tard : il dépend de la nature NOCASE des colonnes)


def analyser_schema(script: str) -> Schema:
    """Analyse un script SQLite (CREATE TABLE / INDEX / TRIGGER) ; remplit aussi le texte PostgreSQL de chaque objet."""
    schema = Schema()
    litteraux_par_instruction = {}
    for texte in decouper_instructions(script):
        m, lit = masquer(texte)
        if re.match(r"\s*CREATE\s+TABLE\b", m, re.I):
            r = re.match(r"\s*CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?(\w+)\s*\(", m, re.I)
            ouvrante = r.end() - 1
            fermante = _parentheses_equilibrees(m, ouvrante)
            t = _analyser_table(r.group(1), m[ouvrante + 1:fermante], lit)
            schema.tables[t.nom] = t
            litteraux_par_instruction[t.nom] = lit
        elif re.match(r"\s*CREATE\s+(UNIQUE\s+)?INDEX\b", m, re.I):
            i = _analyser_index(m, lit, schema)
            schema.index[i.nom] = i
            litteraux_par_instruction["I:" + i.nom] = (m, lit)
        elif re.match(r"\s*CREATE\s+TRIGGER\b", m, re.I):
            d = _analyser_declencheur(texte, m, lit)
            schema.declencheurs[d.nom] = d
        else:
            raise ValueError("instruction de schéma non gérée : " + texte[:80])

    # CITEXT se propage de la clé parent vers les colonnes qui la référencent (PostgreSQL exige le même type de part et d'autre)
    changement = True
    while changement:
        changement = False
        for t in schema.tables.values():
            for fk in t.cles_etrangeres:
                parent = schema.tables.get(fk.table_ref)
                if not parent:
                    raise ValueError(f"{t.nom} référence une table inconnue : {fk.table_ref}")
                for c_enfant, c_parent in zip(fk.colonnes, fk.colonnes_ref):
                    ce, cp = t.colonne(c_enfant), parent.colonne(c_parent)
                    if cp.nocase and not ce.nocase and ce.type_sqlite == "TEXT":
                        ce.nocase = changement = True

    for t in schema.tables.values():
        t.texte_pg = _sql_table(t, schema, litteraux_par_instruction[t.nom])
    for i in schema.index.values():
        m, lit = litteraux_par_instruction["I:" + i.nom]
        i.texte_pg = _sql_index(i, schema, lit)
    return schema


def _expression_pg(texte: str, lit: list) -> str:
    """Traduit une expression de schéma (CHECK, DEFAULT, WHEN...) déjà masquée."""
    return demasquer(_regles_expression(texte, lit), lit).strip()


def _sql_table(t: Table, schema: Schema, lit: list) -> str:
    lignes = []
    for c in t.colonnes:
        s = f"{c.nom.lower()} {type_pg(c.type_sqlite, c.nocase)}"
        if c.identite:
            s = f"{c.nom.lower()} BIGINT GENERATED BY DEFAULT AS IDENTITY"
        if c.defaut is not None:
            s += " DEFAULT " + _expression_pg(c.defaut, lit)
        if c.non_nul and not (len(t.cle) == 1 and t.cle[0] == c.nom):
            s += " NOT NULL"
        if c.unique:
            s += " UNIQUE"
        for ctrl in c.controles:
            s += f" CHECK ({_expression_pg(ctrl, lit)})"
        lignes.append(s)
    if t.cle:
        lignes.append("PRIMARY KEY (" + ", ".join(x.lower() for x in t.cle) + ")")
    lignes += ["UNIQUE (" + ", ".join(x.lower() for x in u) + ")" for u in t.uniques]
    lignes += [f"CHECK ({_expression_pg(c, lit)})" for c in t.controles]
    return f"CREATE TABLE IF NOT EXISTS {t.nom.lower()} (\n    " + ",\n    ".join(lignes) + "\n)"


def sql_cles_etrangeres(t: Table) -> list:
    """ALTER TABLE ... ADD CONSTRAINT pour chaque clé étrangère (ajoutées après la création de toutes les tables)."""
    resultat = []
    for n, fk in enumerate(t.cles_etrangeres, 1):
        suppression = f" ON DELETE {fk.suppression}" if fk.suppression else ""
        resultat.append(
            f"ALTER TABLE {t.nom.lower()} ADD CONSTRAINT fk_{t.nom.lower()}_{n} FOREIGN KEY "
            f"({', '.join(c.lower() for c in fk.colonnes)}) REFERENCES {fk.table_ref.lower()} "
            f"({', '.join(c.lower() for c in fk.colonnes_ref)}){suppression} DEFERRABLE INITIALLY IMMEDIATE")
    return resultat


def _sql_index(i: Index, schema: Schema, lit: list) -> str:
    elements = []
    for e in i.elements:
        simple = re.fullmatch(r"\s*(\w+)\s*(COLLATE\s+NOCASE)?\s*(ASC|DESC)?\s*", e, re.I)
        if simple:
            nom, nocase, sens = simple.group(1), simple.group(2), simple.group(3)
            colonne_citext = schema.tables[i.table].colonne(nom).nocase
            texte = nom.lower() if (not nocase or colonne_citext) else f"(lower({nom.lower()}))"
            elements.append(texte + (f" {sens.upper()}" if sens else ""))
        else:
            elements.append("(" + _expression_pg(e, lit) + ")")
    condition = f" WHERE {_expression_pg(i.condition, lit)}" if i.condition else ""
    return (f"CREATE {'UNIQUE ' if i.unique else ''}INDEX IF NOT EXISTS {i.nom.lower()} ON {i.table.lower()} "
            f"({', '.join(elements)}){condition}")


def instructions_creation(schema: Schema, tables_existantes=()) -> list:
    """Toutes les instructions PostgreSQL pour créer ce qui manque : tables, clés étrangères, index, déclencheurs."""
    existantes = {t.upper() for t in tables_existantes}
    nouvelles = [t for t in schema.tables.values() if t.nom not in existantes]
    instr = [t.texte_pg for t in nouvelles]
    for t in nouvelles:
        instr += sql_cles_etrangeres(t)
    instr += [i.texte_pg for i in schema.index.values()]
    for d in schema.declencheurs.values():
        instr += d.texte_pg
    return instr


def definition_colonne_pg(nom: str, type_sqlite: str, defaut=None, non_nul=False) -> str:
    """Texte « colonne type [DEFAULT x] [NOT NULL] » pour ALTER TABLE ... ADD COLUMN."""
    texte = f"{nom.lower()} {type_pg(type_sqlite)}"
    if defaut is not None:
        m, lit = masquer(str(defaut))
        texte += " DEFAULT " + _expression_pg(m, lit)
    return texte + (" NOT NULL" if non_nul else "")



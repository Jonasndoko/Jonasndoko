class TestSchema(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.schema = sqlpg.enregistrer(database.SCHEMA)

    def test_comptes(self):
        self.assertEqual(len(self.schema.tables), 71)
        self.assertGreaterEqual(len(self.schema.index), 27)
        self.assertEqual(len(self.schema.declencheurs), 9)

    def test_toutes_les_tables_ont_une_cle_primaire(self):
        for t in self.schema.tables.values():
            self.assertTrue(t.cle, t.nom)

    def test_cles_etrangeres_vers_des_tables_connues(self):
        for t in self.schema.tables.values():
            for fk in t.cles_etrangeres:
                self.assertIn(fk.table_ref, self.schema.tables, t.nom)

    def test_types_pg(self):
        sql = self.schema.tables["PAIEMENT"].texte_pg
        self.assertIn("mont_paye BIGINT", sql)
        self.assertIn("matricule CITEXT", sql)
        self.assertNotIn("AUTOINCREMENT", "\n".join(sqlpg.instructions_creation(self.schema)))
        self.assertNotIn("COLLATE NOCASE", "\n".join(sqlpg.instructions_creation(self.schema)))
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY", self.schema.tables["JOURNAL"].texte_pg)

    def test_cles_etrangeres_differables(self):
        fks = [s for t in self.schema.tables.values() for s in sqlpg.sql_cles_etrangeres(t)]
        self.assertTrue(fks)
        self.assertTrue(all("DEFERRABLE INITIALLY IMMEDIATE" in s for s in fks))

    def test_declencheur_avec_sous_requete(self):
        d = self.schema.declencheurs["CANDIDATURE_EXIGE_PAIEMENT"]
        corps = d.texte_pg[0]
        self.assertIn("IF NOT EXISTS", corps.upper().replace("IF  ", "IF "))
        self.assertIn("RAISE EXCEPTION", corps)
        self.assertNotIn(" WHEN ", d.texte_pg[2].upper())

    def test_identites_connues(self):
        self.assertEqual(self.schema.identites["JOURNAL"], "ID_LOG")
        self.assertEqual(self.schema.identites["CLASSE"], "N_CLASSE")

    def test_ordre_de_copie_parents_d_abord(self):
        ordre = pgcopie.ordre_tables(self.schema)
        pos = {n: i for i, n in enumerate(ordre)}
        self.assertEqual(len(ordre), 71)
        for t in self.schema.tables.values():
            for fk in t.cles_etrangeres:
                if fk.table_ref != t.nom:
                    self.assertLess(pos[fk.table_ref], pos[t.nom], f"{fk.table_ref} avant {t.nom}")
        self.assertLess(pos["PAIEMENT"], pos["CANDIDATURE"])


# ============================================================================ traduction de toutes les requêtes du programme
def _sql_de(noeud):
    if isinstance(noeud, ast.Constant) and isinstance(noeud.value, str):
        return noeud.value
    if isinstance(noeud, ast.JoinedStr):
        return "".join(v.value if isinstance(v, ast.Constant) else "X" for v in noeud.values)
    if isinstance(noeud, ast.BinOp) and isinstance(noeud.op, ast.Add):
        a, b = _sql_de(noeud.left), _sql_de(noeud.right)
        return a + b if a is not None and b is not None else None
    return None


def requetes_du_programme():
    debut = re.compile(r"^\s*(SELECT|INSERT|UPDATE|DELETE|WITH|REPLACE)\b", re.I)
    vues = {}
    for f in sorted(glob.glob(os.path.join(DOSSIER, "*.py"))):
        nom = os.path.basename(f)
        if nom.startswith("test_") or nom in ("sqlpg.py", "pgconn.py", "pgcopie.py"):
            continue
        with open(f, encoding="utf-8") as fichier:
            arbre = ast.parse(fichier.read())
        for n in ast.walk(arbre):
            s = _sql_de(n)
            if s and debut.match(s) and len(s) > 20 and re.search(r"\b(FROM|INTO|SET|VALUES)\b", s, re.I):
                m, _ = sqlpg.masquer(s)
                if m.count("(") != m.count(")") or "%s" in m or "%d" in m:     # fragment complété à l'exécution : non testable seul
                    continue
                vues.setdefault(s, (nom, n.lineno))
    return vues


class TestTraductionRequetes(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        sqlpg.enregistrer(database.SCHEMA)
        cls.requetes = requetes_du_programme()

    def test_on_a_trouve_les_requetes(self):
        self.assertGreater(len(self.requetes), 600)

    def test_toutes_se_traduisent_sans_reste_de_sqlite(self):
        interdits = [r"\bCOLLATE\s+NOCASE\b", r"\bGLOB\b", r"\bINSERT\s+OR\b", r"\bREPLACE\s+INTO\b", r"\bAUTOINCREMENT\b",
                     r"\browid\b", r"\bPRAGMA\b"]
        for s, (fichier, ligne) in self.requetes.items():
            for avec in (True, False):
                try:
                    pg = sqlpg.traduire(s, avec)
                except Exception as erreur:
                    self.fail(f"{fichier}:{ligne} : traduction impossible ({erreur}) : {s[:100]}")
                masque, _ = sqlpg.masquer(pg)
                for rx in interdits:
                    self.assertIsNone(re.search(rx, masque, re.I), f"{fichier}:{ligne} contient encore {rx} : {pg[:120]}")
                self.assertEqual(masque.count("("), masque.count(")"), f"{fichier}:{ligne} parenthèses : {pg[:120]}")

    def test_marqueurs_de_parametres_conserves(self):
        for s, (fichier, ligne) in self.requetes.items():
            m, _ = sqlpg.masquer(s.strip().rstrip(";"))
            pg, _ = sqlpg.masquer(sqlpg.traduire(s, True))
            self.assertEqual(m.count("?"), pg.count("%s"), f"{fichier}:{ligne} : {s[:100]}")

    def test_sum_de_booleens_corrige(self):
        for s, (fichier, ligne) in self.requetes.items():
            self.assertIsNone(re.search(r"\bSUM\s*\(\s*[\w.]+\s*(=|<>|<|>)", s, re.I), f"{fichier}:{ligne} : SUM(booléen)")

    def test_pas_de_fonctions_sqlite_sans_equivalent(self):
        for s, (fichier, ligne) in self.requetes.items():
            m, _ = sqlpg.masquer(s)
            self.assertIsNone(re.search(r"\b(strftime|julianday|datetime|ifnull|group_concat|instr|printf|typeof)\s*\(", m, re.I),
                              f"{fichier}:{ligne} : fonction propre à SQLite")
            self.assertIsNone(re.search(r"\b(MAX|MIN)\s*\([^()]*,[^()]*\)", m, re.I), f"{fichier}:{ligne} : MAX/MIN à 2 arguments")

    def test_regles_unitaires(self):
        t = lambda s, p=True: sqlpg.traduire(s, p)
        self.assertEqual(t("SELECT * FROM A WHERE X = ? COLLATE NOCASE"), "SELECT * FROM A WHERE LOWER(X) = LOWER(%s)")
        self.assertIn("ON CONFLICT DO NOTHING", t("INSERT OR IGNORE INTO PERCEPTEUR (ID_USER) VALUES (?)"))
        rempl = t("INSERT OR REPLACE INTO PHOTO_ELEVE (MATRICULE, PHOTO, DATE_PHOTO, PRIS_PAR) VALUES (?,?,?,?)")
        self.assertIn("ON CONFLICT (matricule) DO UPDATE SET PHOTO = EXCLUDED.PHOTO", rempl)
        self.assertIn("NULLS FIRST", t("SELECT A FROM T ORDER BY A"))
        self.assertIn("DESC NULLS LAST", t("SELECT A FROM T ORDER BY A DESC"))
        self.assertIn("IS NOT DISTINCT FROM", t("SELECT 1 FROM T WHERE A IS ?"))
        self.assertIn("ILIKE", t("SELECT 1 FROM T WHERE A LIKE ?"))
        self.assertEqual(t("SELECT '50%' FROM T WHERE A = ?"), "SELECT '50%%' FROM T WHERE A = %s")
        self.assertEqual(t("SELECT '50%' FROM T", False), "SELECT '50%' FROM T")
        self.assertNotIn("LOWER(", t("SELECT DISTINCT A FROM T ORDER BY A COLLATE NOCASE"))
        self.assertEqual(t('SELECT COUNT(*) FROM "ELEVE"'), 'SELECT COUNT(*) FROM "eleve"')


class TestGlob(unittest.TestCase):
    def test_motif_annee_equivalent_a_sqlite(self):
        motif = "[0-9][0-9][0-9][0-9]-[0-9][0-9][0-9][0-9]"
        regex = re.compile(sqlpg._glob_vers_regex(motif))
        c = sqlite3.connect(":memory:")
        for valeur in ("2025-2026", "2025-26", "x2025-2026", "2025-2026x", "", "20252026", "2025-2026\n"):
            attendu = c.execute("SELECT ? GLOB ?", (valeur, motif)).fetchone()[0]
            self.assertEqual(bool(regex.match(valeur)) and not valeur.endswith("\n"), bool(attendu), repr(valeur))

    def test_jokers(self):
        c = sqlite3.connect(":memory:")
        for motif, valeur in (("a*c", "abbbc"), ("a?c", "abc"), ("a?c", "abbc"), ("[a-c]x", "bx"), ("[^a-c]x", "bx"), ("a.c", "abc")):
            regex = re.compile(sqlpg._glob_vers_regex(motif))
            self.assertEqual(bool(regex.match(valeur)), bool(c.execute("SELECT ? GLOB ?", (valeur, motif)).fetchone()[0]), (motif, valeur))


# ============================================================================ couche pgconn avec une fausse connexion
class FausseErreur(Exception):
    def __init__(self, sqlstate, primaire="", detail="", table="", colonne="", contrainte=""):
        super().__init__(primaire)
        self.sqlstate = sqlstate
        self.diag = SimpleNamespace(message_primary=primaire, message_detail=detail, table_name=table, column_name=colonne,
                                    constraint_name=contrainte)


class FauxCurseur:
    def __init__(self, lignes=(), noms=(), rowcount=0):
        self._l = list(lignes)
        self.description = [SimpleNamespace(name=n) for n in noms] or None
        self.rowcount = rowcount

    def fetchall(self):
        return self._l

    def fetchone(self):
        return self._l[0] if self._l else None


class FauxPG:
    """Enregistre les instructions ; suit l'état de transaction comme PostgreSQL (BEGIN / COMMIT / ROLLBACK)."""

    def __init__(self):
        self.vu = []
        self.statut = 0
        self.reponses = []                           # [(motif regex, curseur ou exception)]
        parent = self

        class _Info:
            transaction_status = property(lambda self: parent.statut)
        self.info = _Info()
        self.ferme = False

    def execute(self, sql, params=None):
        self.vu.append((sql, params))
        u = sql.strip().upper()
        if u.startswith("BEGIN"):
            self.statut = 2
        elif u in ("COMMIT", "ROLLBACK"):
            self.statut = 0
        for motif, rep in self.reponses:
            if re.search(motif, sql, re.I | re.S):
                if isinstance(rep, Exception):
                    raise rep
                return rep
        return FauxCurseur()

    def close(self):
        self.ferme = True

    def sqls(self):
        return [s for s, _ in self.vu]


def faux_conn():
    sqlpg.enregistrer(database.SCHEMA)
    pg = FauxPG()
    c = pgconn.Connexion(pg, "postgresql://test/db")
    c._erreur_pg = FausseErreur
    return c, pg


class TestConnexion(unittest.TestCase):
    def test_lecture_n_ouvre_pas_de_transaction(self):
        c, pg = faux_conn()
        pg.reponses.append((r"^SELECT", FauxCurseur([(5,)], ["n"])))
        self.assertEqual(c.execute("SELECT COUNT(*) AS N FROM ELEVE").fetchone()[0], 5)
        self.assertFalse(c.in_transaction)
        self.assertNotIn("BEGIN", pg.sqls())

    def test_ecriture_ouvre_transaction_et_savepoint(self):
        c, pg = faux_conn()
        c.execute("UPDATE ELEVE SET ACTIF = ? WHERE MATRICULE = ?", (False, "0001/26"))
        s = pg.sqls()
        self.assertEqual(s[0], "BEGIN")
        self.assertEqual(s[1], "SAVEPOINT gestsco_instr")
        self.assertTrue(s[2].startswith("UPDATE ELEVE"))
        self.assertEqual(pg.vu[2][1], (0, "0001/26"))           # bool -> 0
        self.assertEqual(s[3], "RELEASE SAVEPOINT gestsco_instr")
        self.assertTrue(c.in_transaction)
        c.commit()
        self.assertFalse(c.in_transaction)
        self.assertEqual(s[-1] if False else pg.sqls()[-1], "COMMIT")

    def test_echec_annule_seulement_l_instruction(self):
        c, pg = faux_conn()
        pg.reponses.append((r"^INSERT", FausseErreur("23505", "doublon", "Key (n_recu)=(R1) already exists.", "candidature")))
        with self.assertRaises(sqlite3.IntegrityError) as ctx:
            c.execute("INSERT INTO CANDIDATURE (N_RECU) VALUES (?)", ("R1",))
        self.assertIn("N_RECU", str(ctx.exception))
        self.assertIn("ROLLBACK TO SAVEPOINT gestsco_instr", pg.sqls())
        self.assertTrue(c.in_transaction)                          # comme sqlite3 : la transaction reste ouverte
        c.rollback()
        self.assertFalse(c.in_transaction)

    def test_lastrowid_par_returning(self):
        c, pg = faux_conn()
        pg.reponses.append((r"RETURNING n_cand", FauxCurseur([(42,)], ["n_cand"], 1)))
        cur = c.execute("INSERT INTO CANDIDATURE (NOM) VALUES (?)", ("X",))
        self.assertEqual(cur.lastrowid, 42)
        self.assertTrue(any("RETURNING n_cand" in s for s in pg.sqls()))
        c2, pg2 = faux_conn()
        c2.execute("INSERT INTO DROIT (ID_USER, MODULE, DROIT) VALUES (?,?,?)", (1, "a", "b"))     # clé composite : pas de RETURNING
        self.assertFalse(any("RETURNING" in s for s in pg2.sqls()))

    def test_begin_immediate_pose_le_verrou(self):
        c, pg = faux_conn()
        c.execute("BEGIN IMMEDIATE")
        self.assertEqual(pg.sqls()[0], "BEGIN")
        self.assertIn("pg_advisory_xact_lock", pg.sqls()[1])
        self.assertEqual(pg.vu[1][1], (pgconn.CLE_VERROU_ECRITURE,))
        c.execute("BEGIN IMMEDIATE")                               # déjà dans une transaction : pas de second BEGIN
        self.assertEqual(pg.sqls().count("BEGIN"), 1)

    def test_with_valide_sans_fermer(self):
        c, pg = faux_conn()
        with c:
            c.execute("DELETE FROM ENCAISSEMENT WHERE N_ENC = ?", (1,))
        self.assertIn("COMMIT", pg.sqls())
        self.assertFalse(pg.ferme)
        with self.assertRaises(ValueError):
            with c:
                c.execute("DELETE FROM ENCAISSEMENT WHERE N_ENC = ?", (2,))
                raise ValueError("x")
        self.assertIn("ROLLBACK", pg.sqls())
        self.assertFalse(pg.ferme)

    def test_pragma_user_version(self):
        c, pg = faux_conn()
        pg.reponses.append((r"SELECT valeur FROM gestsco_meta", FauxCurseur([("17",)], ["valeur"])))
        self.assertEqual(c.execute("PRAGMA user_version").fetchone()[0], 17)
        c.execute("PRAGMA user_version = 18")
        self.assertTrue(any("ON CONFLICT (cle) DO UPDATE" in s for s in pg.sqls()))

    def test_pragma_foreign_keys_et_differes(self):
        c, pg = faux_conn()
        self.assertEqual(c.execute("PRAGMA foreign_keys").fetchone()[0], 1)
        c.execute("PRAGMA foreign_keys = OFF")
        self.assertEqual(c.execute("PRAGMA foreign_keys").fetchone()[0], 0)
        c.execute("PRAGMA defer_foreign_keys = ON")                # hors transaction : sans effet
        self.assertNotIn("SET CONSTRAINTS ALL DEFERRED", pg.sqls())
        c.execute("BEGIN IMMEDIATE")
        c.execute("PRAGMA defer_foreign_keys = ON")
        self.assertIn("SET CONSTRAINTS ALL DEFERRED", pg.sqls())

    def test_drop_trigger_et_alter(self):
        c, pg = faux_conn()
        c.execute('DROP TRIGGER "PAIEMENT_NO_UPDATE"')
        self.assertIn("DROP TRIGGER IF EXISTS paiement_no_update ON paiement", pg.sqls())
        c.execute('ALTER TABLE "ELEVE" ADD COLUMN "X" BIGINT DEFAULT 0')
        self.assertIn('ALTER TABLE "eleve" ADD COLUMN "x" BIGINT DEFAULT 0'.replace('"', ""), [s.replace('"', "") for s in pg.sqls()])

    def test_executescript_cree_ce_qui_manque(self):
        c, pg = faux_conn()
        pg.reponses.append((r"relkind = 'r'", FauxCurseur([("utilisateur",), ("journal",)], ["relname"])))
        c.executescript(database.SCHEMA)
        s = "\n".join(pg.sqls())
        self.assertIn("CREATE TABLE IF NOT EXISTS eleve", s)
        self.assertNotIn("CREATE TABLE IF NOT EXISTS utilisateur", s)       # existait déjà
        self.assertIn("CREATE TRIGGER candidature_exiger_paiement".replace("exiger", "exige"), s)
        self.assertIn("ALTER TABLE paiement ADD CONSTRAINT", s)

    def test_executescript_ignore_les_tables_de_reconstruction_sqlite(self):
        c, pg = faux_conn()
        pg.reponses.append((r"relkind = 'r'", FauxCurseur([], ["relname"])))
        c.executescript("CREATE TABLE UTILISATEUR_NEW (ID INTEGER);")
        self.assertFalse(any("utilisateur_new" in s.lower() for s in pg.sqls()))

    def test_table_info_et_liens_emules(self):
        c, pg = faux_conn()
        pg.reponses.append((r"format_type", FauxCurseur([(0, "ID_USER", "bigint", True, None, True)], [""] * 6)))
        r = c.execute('PRAGMA table_info("UTILISATEUR")').fetchall()
        self.assertEqual(tuple(r[0]), (0, "ID_USER", "INTEGER", 1, None, 1))
        self.assertEqual(r[0]["name"], "ID_USER")
        pg.reponses.insert(0, (r"pg_constraint", FauxCurseur([("PAIEMENT", 7, 0, "INSCRIRE", "ANNEESCO", "ANNEESCO", "a"),
                                                              ("PAIEMENT", 7, 1, "INSCRIRE", "MATRICULE", "MATRICULE", "a")], [""] * 7)))
        liens = c.execute('PRAGMA foreign_key_list("PAIEMENT")').fetchall()
        self.assertEqual((liens[1][2], liens[1][3], liens[1]["table"], liens[1]["from"]), ("INSCRIRE", "MATRICULE", "INSCRIRE", "MATRICULE"))
        self.assertEqual(liens[0]["id"], liens[1]["id"])


class TestLignesEtErreurs(unittest.TestCase):
    def test_ligne_acces_par_nom_sans_casse(self):
        cur = pgconn.Curseur([(1, "a", None)], ["id_user", "login", "x"])
        l = cur.fetchone()
        self.assertEqual((l["ID_USER"], l["login"], l[1], l[-1]), (1, "a", "a", None))
        self.assertEqual(l.keys(), ["ID_USER", "LOGIN", "X"])
        self.assertEqual(dict(l), {"ID_USER": 1, "LOGIN": "a", "X": None})
        with self.assertRaises(IndexError):
            l["absent"]
        self.assertIsNone(cur.fetchone())

    def test_messages_d_erreur_comme_sqlite(self):
        e = pgconn.convertir_erreur(FausseErreur("23505", "x", "Key (anneesco, num_seq)=(2026-2027, 1) already exists.", "paiement"))
        self.assertIsInstance(e, sqlite3.IntegrityError)
        self.assertEqual(str(e), "UNIQUE constraint failed: PAIEMENT.ANNEESCO, PAIEMENT.NUM_SEQ")
        self.assertEqual(str(pgconn.convertir_erreur(FausseErreur("23503", "x"))), "FOREIGN KEY constraint failed")
        self.assertEqual(str(pgconn.convertir_erreur(FausseErreur("23502", "x", table="eleve", colonne="nom"))),
                         "NOT NULL constraint failed: ELEVE.NOM")
        self.assertTrue(str(pgconn.convertir_erreur(FausseErreur("23514", "x", contrainte="paiement_mont_paye_check"))).startswith("CHECK"))
        trig = pgconn.convertir_erreur(FausseErreur("23000", "Candidature refusée : aucun paiement valide des frais d'inscription"))
        self.assertIsInstance(trig, sqlite3.IntegrityError)
        self.assertIn("frais d'inscription", str(trig))             # inscription.py lit ce texte
        self.assertIsInstance(pgconn.convertir_erreur(FausseErreur("42P01", "relation absente")), sqlite3.OperationalError)

    def test_schema_isole_unique_pour_memoire(self):
        self.assertNotEqual(pgconn.schema_de(":memory:"), pgconn.schema_de(":memory:"))
        self.assertEqual(pgconn.schema_de("/tmp/a.db"), pgconn.schema_de("/tmp/a.db"))

    def test_url_sans_mot_de_passe(self):
        self.assertEqual(pgconn.nettoyer_url("postgresql://gestsco:secret@h:5432/db"), "postgresql://gestsco@h:5432/db")

    def test_controle_donnees_sqlite_refusees(self):
        self.assertEqual(pgcopie._controler("T", "C", 5, "BIGINT", 1), "")
        self.assertIn("pas un nombre", pgcopie._controler("T", "C", "abc", "BIGINT", 1))
        self.assertIn("nul", pgcopie._controler("T", "C", "a\x00b", "TEXT", 1))
        self.assertIn("binaire", pgcopie._controler("T", "C", b"x", "CITEXT", 1))
        self.assertEqual(pgcopie._controler("T", "C", None, "BIGINT", 1), "")


